import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import AuthIPBlacklistView from '@/custom/views/AuthIPBlacklistView.vue'
import { authIPBlacklistAPI, authIPTargetSummary, formatAuthIPTime, type AuthIPEntry } from '@/custom/authIpBlacklist'
import { customRoutes } from '@/custom/routes'

const api = vi.hoisted(() => ({ get: vi.fn(), put: vi.fn(), post: vi.fn() }))
vi.mock('@/api/client', () => ({ apiClient: api }))
const config = { enabled: false, threshold: 10, window_seconds: 7200, block_seconds: 900, block_mode: 'timed', version: 1, aggregation_mode: 'network', network_ipv4_prefix: 24, network_ipv6_prefix: 64 }
const entry: AuthIPEntry = {
  id: 8, ip: '61.120.9.25', generation: 3, blocked: true,
  blocked_at: '2026-10-13T12:32:32Z', trigger_path: '/api/v1/auth/login', trigger_count: 10,
  window_seconds: 7200, first_event_at: '2026-10-13T11:12:39Z', last_event_at: '2026-10-13T12:32:32Z', rule_version: 2, source: 'auto', reason: ''
}
function render() {
  return mount(AuthIPBlacklistView, { global: { stubs: {
    AppLayout: { template: '<main><slot /></main>' },
    ConfirmDialog: { props: ['show', 'message'], emits: ['confirm', 'cancel'], template: '<div v-if="show"><p>{{ message }}</p><button data-testid="confirm" @click="$emit(\'confirm\')">确认移除</button></div>' }
  } } })
}
beforeEach(() => {
  vi.resetAllMocks()
  api.get.mockImplementation(async (url: string) => ({ data: url.endsWith('/config') ? config : { items: [entry], total: 1, page: 1, page_size: 20, pages: 1 } }))
  api.put.mockResolvedValue({ data: { ...config, version: 2 } })
  api.post.mockResolvedValue({ data: { ...entry, blocked: false, generation: 4 } })
})

describe('IP 黑名单管理', () => {
  it('网段范围保存及非法前缀阻止提交', async () => {
    const wrapper = render()
    await flushPromises()
    expect(wrapper.get('[data-testid="aggregation"]').element).toHaveProperty('value', 'network')
    expect(wrapper.text()).toContain('正常用户')
    await wrapper.get('[data-testid="ipv4-prefix"]').setValue(0)
    await wrapper.get('form').trigger('submit')
    expect(api.put).not.toHaveBeenCalled()
    await wrapper.get('[data-testid="ipv4-prefix"]').setValue(25)
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(api.put).toHaveBeenCalledWith('/admin/ip-blacklist/config', { ...config, network_ipv4_prefix: 25 })
    await wrapper.get('[data-testid="aggregation"]').setValue('ip')
    await wrapper.get('form').trigger('submit')
    await flushPromises()
    expect(api.put).toHaveBeenLastCalledWith('/admin/ip-blacklist/config', { ...config, version: 2, aggregation_mode: 'ip', network_ipv4_prefix: 25 })
  })

  it('手动通配符确认显示实际网段和地址范围', async () => {
    const wrapper = render()
    await flushPromises()
    await wrapper.get('[data-testid="manual-open"]').trigger('click')
    await wrapper.get('[data-testid="manual-ip"]').setValue('210.230.206.*')
    await wrapper.get('[data-testid="manual-reason"]').setValue('同网段恶意探查')
    await wrapper.get('[data-testid="manual-form"]').trigger('submit')
    expect(wrapper.text()).toContain('210.230.206.0/24')
    expect(wrapper.text()).toContain('256 个 IP')
    await wrapper.get('[data-testid="confirm"]').trigger('click')
    await flushPromises()
    expect(api.post).toHaveBeenCalledWith('/admin/ip-blacklist/entries', { ip: '210.230.206.*', block_mode: 'permanent', block_seconds: 0, reason: '同网段恶意探查' })
    expect(authIPTargetSummary('210.230.*')).toBe('210.230.*')
    expect(authIPTargetSummary('210.230.206.0/24/25')).toBe('210.230.206.0/24/25')
  })
  it('手动永久封禁需确认，提交原因，刷新显示来源而不伪造失败统计', async () => {
    const manualEntry: AuthIPEntry = { ...entry, ip: '192.0.2.40', source: 'manual', reason: '确认恶意扫描', trigger_path: '', trigger_count: 0, window_seconds: 0, first_event_at: null, last_event_at: null, rule_version: 0 }
    api.post.mockImplementation(async () => {
      api.get.mockResolvedValue({ data: { items: [manualEntry], total: 1, page: 1, page_size: 20, pages: 1 } })
      return { data: manualEntry }
    })
    const wrapper = render()
    await flushPromises()
    await wrapper.get('[data-testid="manual-open"]').trigger('click')
    expect(wrapper.get('[data-testid="manual-mode"]').element).toHaveProperty('value', 'permanent')
    await wrapper.get('[data-testid="manual-ip"]').setValue(' 192.0.2.40 ')
    await wrapper.get('[data-testid="manual-reason"]').setValue(' 确认恶意扫描 ')
    await wrapper.get('[data-testid="manual-form"]').trigger('submit')
    expect(api.post).not.toHaveBeenCalled()
    expect(wrapper.text()).toContain('确认封禁 192.0.2.40（永久）')
    await wrapper.get('[data-testid="confirm"]').trigger('click')
    await flushPromises()
    expect(api.post).toHaveBeenCalledWith('/admin/ip-blacklist/entries', { ip: '192.0.2.40', block_mode: 'permanent', block_seconds: 0, reason: '确认恶意扫描' })
    expect(wrapper.text()).toContain('管理员手动')
    expect(wrapper.text()).toContain('确认恶意扫描')
    expect(wrapper.text()).not.toContain('0 次 / 0 分钟')
    expect(wrapper.text()).not.toContain('1970')
    expect(wrapper.find('[data-testid="manual-form"]').exists()).toBe(false)
  })
  it('手动限时封禁按分钟验证并以秒提交，与自动规则独立', async () => {
    const wrapper = render()
    await flushPromises()
    await wrapper.get('[data-testid="manual-open"]').trigger('click')
    await wrapper.get('[data-testid="manual-ip"]').setValue('2001:db8::40')
    await wrapper.get('[data-testid="manual-reason"]').setValue('高频探查')
    await wrapper.get('[data-testid="manual-mode"]').setValue('timed')
    await wrapper.get('[data-testid="manual-minutes"]').setValue('0')
    await wrapper.get('[data-testid="manual-form"]').trigger('submit')
    expect(wrapper.text()).toContain('1–1440分钟')
    expect(wrapper.find('[data-testid="confirm"]').exists()).toBe(false)
    await wrapper.get('[data-testid="manual-minutes"]').setValue('45')
    await wrapper.get('[data-testid="manual-form"]').trigger('submit')
    expect(wrapper.text()).toContain('45 分钟')
    await wrapper.get('[data-testid="confirm"]').trigger('click')
    await flushPromises()
    expect(api.post).toHaveBeenCalledWith('/admin/ip-blacklist/entries', { ip: '2001:db8::40', block_mode: 'timed', block_seconds: 2700, reason: '高频探查' })
    expect(api.put).not.toHaveBeenCalled()
  })
  it('拒绝空原因与超长原因，不发送手动封禁请求', async () => {
    const wrapper = render()
    await flushPromises()
    await wrapper.get('[data-testid="manual-open"]').trigger('click')
    await wrapper.get('[data-testid="manual-ip"]').setValue('192.0.2.40')
    for (const reason of [' ', '恶'.repeat(501)]) {
      await wrapper.get('[data-testid="manual-reason"]').setValue(reason)
      await wrapper.get('[data-testid="manual-form"]').trigger('submit')
      expect(wrapper.text()).toContain('1–500字')
      expect(wrapper.find('[data-testid="confirm"]').exists()).toBe(false)
    }
    expect(api.post).not.toHaveBeenCalled()
  })
  it('重复手动添加409刷新名单，保留输入并显示已有封禁提示', async () => {
    api.post.mockRejectedValue({ status: 409, message: '该 IP 已被封禁，请先解除原封禁' })
    const wrapper = render()
    await flushPromises()
    await wrapper.get('[data-testid="manual-open"]').trigger('click')
    await wrapper.get('[data-testid="manual-ip"]').setValue(entry.ip)
    await wrapper.get('[data-testid="manual-reason"]').setValue('人工确认')
    await wrapper.get('[data-testid="manual-form"]').trigger('submit')
    await wrapper.get('[data-testid="confirm"]').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('该 IP 已被封禁')
    expect(wrapper.get('[data-testid="manual-ip"]').element).toHaveProperty('value', entry.ip)
    expect(api.get).toHaveBeenCalledTimes(3)
    expect(wrapper.find('[data-testid="confirm"]').exists()).toBe(false)
  })
  it('无效IP由服务端拒绝并保留表单，空时间不转换为1970', async () => {
    api.post.mockRejectedValue({ status: 400, message: '请输入完整有效的 IPv4 或 IPv6 地址' })
    const wrapper = render()
    await flushPromises()
    await wrapper.get('[data-testid="manual-open"]').trigger('click')
    await wrapper.get('[data-testid="manual-ip"]').setValue('192.0.2.0/24')
    await wrapper.get('[data-testid="manual-reason"]').setValue('扫描')
    await wrapper.get('[data-testid="manual-form"]').trigger('submit')
    await wrapper.get('[data-testid="confirm"]').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('请输入完整有效')
    expect(wrapper.find('[data-testid="manual-form"]').exists()).toBe(true)
    expect(formatAuthIPTime(null, 'Asia/Shanghai')).toBe('—')
  })
  it('保存以分钟输入、以秒提交，并附带配置版本', async () => {
    const wrapper = render()
    await flushPromises()
    expect(wrapper.get('[data-testid="minutes"]').element).toHaveProperty('value', '120')
    await wrapper.get('[data-testid="minutes"]').setValue('180')
    await wrapper.get('[data-testid="enabled"]').setValue(true)
    await wrapper.findAll('form')[0].trigger('submit')
    await flushPromises()
    expect(api.put).toHaveBeenCalledWith('/admin/ip-blacklist/config', { ...config, enabled: true, window_seconds: 10800 })
    expect(wrapper.get('[data-testid="cooldown"]').element).toHaveProperty('value', '15')
    expect(wrapper.text()).toContain('成功操作不计数')
    expect(wrapper.text()).toContain('已有临时封禁到期恢复')
  })
  it('永久模式须管理员解除，并保持临时时长供以后切回', async () => {
    api.put.mockImplementation(async (_url: string, value: object) => ({ data: { ...value, version: 2 } }))
    const wrapper = render()
    await flushPromises()
    await wrapper.get('[data-testid="cooldown"]').setValue('')
    await wrapper.get('[data-testid="block-mode"]').setValue('permanent')
    expect(wrapper.find('[data-testid="cooldown"]').exists()).toBe(false)
    expect(wrapper.text()).toContain('永久封禁：管理员移除')
    await wrapper.findAll('form')[0].trigger('submit')
    await flushPromises()
    expect(api.put).toHaveBeenLastCalledWith('/admin/ip-blacklist/config', { ...config, block_mode: 'permanent' })
    expect(wrapper.text()).toContain('修改规则不会改变已有记录的期限')
    await wrapper.get('[data-testid="block-mode"]').setValue('timed')
    expect(wrapper.get('[data-testid="cooldown"]').element).toHaveProperty('value', '15')
    await wrapper.get('[data-testid="cooldown"]').setValue('45')
    await wrapper.findAll('form')[0].trigger('submit')
    await flushPromises()
    expect(api.put).toHaveBeenLastCalledWith('/admin/ip-blacklist/config', { ...config, block_seconds: 2700, version: 2 })
  })
  it('重新打开时正确载入永久模式和临时记录期限', async () => {
    api.get.mockImplementation(async (url: string) => ({ data: url.endsWith('/config') ? { ...config, block_mode: 'permanent' } : { items: [{ ...entry, blocked_until: '2026-10-13T12:47:32Z' }], total: 1, page: 1, page_size: 20, pages: 1 } }))
    const wrapper = render()
    await flushPromises()
    expect(wrapper.get('[data-testid="block-mode"]').element).toHaveProperty('value', 'permanent')
    expect(wrapper.find('[data-testid="cooldown"]').exists()).toBe(false)
    expect(wrapper.text()).toContain('须联系管理员移除')
    expect(wrapper.text()).toContain('到期：')
  })
  it('配置读取失败时禁止保存默认值', async () => {
    api.get.mockRejectedValue({ status: 503, message: '防护数据库暂时不可用' })
    const wrapper = render()
    await flushPromises()
    expect(wrapper.get('[data-testid="save"]').attributes('disabled')).toBeDefined()
    await wrapper.findAll('form')[0].trigger('submit')
    expect(api.put).not.toHaveBeenCalled()
    expect(wrapper.text()).toContain('防护数据库暂时不可用')
  })
  it('精确搜索和分页传递到服务器', async () => {
    api.get.mockImplementation(async (url: string, options?: { params: { page: number } }) => ({ data: url.endsWith('/config') ? config : { items: [entry], total: 21, page: options?.params.page ?? 1, page_size: 20, pages: 2 } }))
    const wrapper = render()
    await flushPromises()
    await wrapper.get('[data-testid="search"]').setValue(' 61.120.9.25 ')
    await wrapper.findAll('form')[1].trigger('submit')
    await flushPromises()
    expect(api.get).toHaveBeenLastCalledWith('/admin/ip-blacklist/entries', { params: { ip: '61.120.9.25', page: 1, page_size: 20 } })
    await wrapper.findAll('button').find(button => button.text() === '下一页')!.trigger('click')
    await flushPromises()
    expect(api.get).toHaveBeenLastCalledWith('/admin/ip-blacklist/entries', { params: { ip: '61.120.9.25', page: 2, page_size: 20 } })
  })
  it('确认解封携带状态版本，409刷新名单并要求再次确认', async () => {
    api.post.mockRejectedValue({ status: 409 })
    const wrapper = render()
    await flushPromises()
    await wrapper.findAll('button').find(button => button.text() === '移除')!.trigger('click')
    expect(api.post).not.toHaveBeenCalled()
    await wrapper.get('[data-testid="confirm"]').trigger('click')
    await flushPromises()
    expect(api.post).toHaveBeenCalledWith('/admin/ip-blacklist/entries/8/unblock', { generation: 3 })
    expect(wrapper.text()).toContain('名单状态已变化')
    expect(wrapper.find('[data-testid="confirm"]').exists()).toBe(false)
    expect(api.get).toHaveBeenCalledTimes(3)
  })
  it('配置409读取当前版本后再保存', async () => {
    api.put.mockRejectedValue({ status: 409 })
    const wrapper = render()
    await flushPromises()
    await wrapper.findAll('form')[0].trigger('submit')
    await flushPromises()
    expect(wrapper.text()).toContain('请重新确认后保存')
    expect(api.get).toHaveBeenCalledTimes(3)
  })
  it('解封成功立即刷新，界面标注时区并显示首末时间', async () => {
    const wrapper = render()
    await flushPromises()
    expect(wrapper.text()).toContain('页面时间：')
    expect(wrapper.text()).toContain('10 次 / 120 分钟')
    await wrapper.findAll('button').find(button => button.text() === '移除')!.trigger('click')
    await wrapper.get('[data-testid="confirm"]').trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('61.120.9.25 已解封')
    expect(api.get).toHaveBeenCalledTimes(3)
  })
  it('路由要求管理员，时间转换只做一次', async () => {
    const route = customRoutes.find(record => record.path === '/admin/ip-blacklist')
    expect(route?.meta).toMatchObject({ requiresAuth: true, requiresAdmin: true })
    expect(formatAuthIPTime(entry.blocked_at, 'Asia/Shanghai')).toContain('20:32:32')
    expect(formatAuthIPTime('invalid', 'Asia/Shanghai')).toBe('—')
    await authIPBlacklistAPI.list('', 1)
    expect(api.get).toHaveBeenCalledWith('/admin/ip-blacklist/entries', { params: { ip: '', page: 1, page_size: 20 } })
  })
})
